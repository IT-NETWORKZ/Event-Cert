// Returns [{ id, label, items }] for a tab + language (falls back to English)
export const getCategories = (type, lang) => {
  const pack = TEXT[lang] || TEXT.en;
  return (STRUCTURE[type] || []).map((id) => ({
    id,
    label: pack.labels[id] || TEXT.en.labels[id],
    items: pack.items[id] || TEXT.en.items[id],
  }));
};